/**
 * ВРЕМЕННЫЕ данные раздела «Архив». Будут заменены ответом бэкенда.
 *
 * Сканы лежат статикой: public/photos/archive/<slug>/{full,thumb}.
 * Оригиналы и полные расшифровки — в raw/archive/<slug> (immutable, не в бандле).
 */
function scan(slug: string, file: string, alt: string): MediaRef {
  return {
    id: `${slug}/${file}`,
    key: `/photos/archive/${slug}/full/${file}`,
    width: 1200,
    height: 1600,
    blurhash: '',
    alt,
    status: 'ready',
  };
}

