/**
 * ВРЕМЕННЫЕ моковые данные летописи обители для предпросмотра UI.
 * Будут заменены ответом бэкенда после его подключения.
 *
 * Фото событий лежат статикой в public/photos/events/<slug>/{full,thumb}.
 * Оригиналы-источники — в raw/events/<slug>/photos (immutable, не в бандле).
 */
function eventMedia(slug: string, file: string, alt: string): MediaRef {
  return {
    id: `${slug}/${file}`,
    key: `/photos/events/${slug}/full/${file}`,
    width: 1000,
    height: 1000,
    blurhash: '',
    alt,
    status: 'ready',
  };
}

